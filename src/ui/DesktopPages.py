"""View widgets; game actions are connected by DesktopWindow only."""
from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (QBoxLayout, QButtonGroup, QCheckBox, QComboBox, QFrame,
    QHBoxLayout, QListWidget, QPlainTextEdit, QProgressBar, QSpinBox,
    QVBoxLayout, QWidget)

from src.ui.DesktopStyle import button, card, field, label, row


def spin(value, maximum, step=1, minimum=0):
    widget = QSpinBox()
    widget.setRange(minimum, maximum)
    widget.setSingleStep(step)
    widget.setValue(value)
    return widget


class RunPage(QWidget):
    kind_changed = Signal(str)

    def __init__(self):
        super().__init__()
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(16)
        self.notice = QFrame()
        self.notice.setObjectName('notice')
        notice_layout = QHBoxLayout(self.notice)
        notice_layout.setContentsMargins(16, 10, 12, 10)
        self.notice_text = label('首次使用请先完成设置。', wrap=True)
        self.notice_button = button('前往设置', 'quiet')
        notice_layout.addWidget(self.notice_text, 1)
        notice_layout.addWidget(self.notice_button)
        layout.addWidget(self.notice)
        columns = QHBoxLayout()
        self.columns = columns
        columns.setSpacing(16)
        left, right = QVBoxLayout(), QVBoxLayout()
        left.setSpacing(16)
        right.setSpacing(16)
        columns.addLayout(left, 6)
        columns.addLayout(right, 4)

        target, target_layout = card('01  选择任务')
        self.kind_group = QButtonGroup(self)
        kind_row = QHBoxLayout()
        self.kind_buttons = {}
        for key, name in [('tacet', '无音区声骸'), ('boss', 'Boss 声骸'), ('materials', '培养材料')]:
            control = button(name, 'segment')
            control.setCheckable(True)
            control.setProperty('kind', key)
            self.kind_group.addButton(control)
            self.kind_buttons[key] = control
            kind_row.addWidget(control)
        self.kind_buttons['tacet'].setChecked(True)
        self.kind_group.buttonClicked.connect(lambda control: self.kind_changed.emit(control.property('kind')))
        target_layout.addLayout(kind_row)
        self.stage = QComboBox()
        self.stage.setMinimumWidth(160)
        self.stage.addItem('先读取游戏中的关卡列表', '')
        self.catalog = button('读取关卡')
        target_layout.addLayout(row(self.stage, self.catalog))
        self.task_note = label('关卡列表从当前账号读取。开始前会重新检查实际队伍。', 'muted', True)
        target_layout.addWidget(self.task_note)
        left.addWidget(target)

        resources, budget_layout = card('02  设置本轮额度')
        self.claim_rewards = QCheckBox('打完领取奖励')
        self.claim_rewards.setChecked(True)
        budget_layout.addWidget(self.claim_rewards)
        self.waveplates, self.claims = spin(120, 360, 20), spin(2, 6, minimum=1)
        budget_row = QHBoxLayout()
        budget_row.setSpacing(16)
        budget_row.addLayout(field('最多消耗波片', self.waveplates), 1)
        budget_row.addLayout(field('最多领取份数', self.claims), 1)
        budget_layout.addLayout(budget_row)
        self.budget_note = label('双倍领取计 2 份。达到任一额度即结束本轮。', 'muted', True)
        budget_layout.addWidget(self.budget_note)
        self.refill = QCheckBox('波片不足时，允许在额度内补充')
        budget_layout.addWidget(self.refill)
        self.refill_fields = QWidget()
        refill_layout = QHBoxLayout(self.refill_fields)
        refill_layout.setContentsMargins(0, 0, 0, 0)
        refill_layout.setSpacing(16)
        self.solvents, self.reserve = spin(0, 6), spin(0, 240, 60)
        refill_layout.addLayout(field('结晶溶剂 / 个', self.solvents))
        refill_layout.addLayout(field('储备波片', self.reserve))
        self.refill_fields.hide()
        self.refill.toggled.connect(self.refill_fields.setVisible)
        budget_layout.addWidget(self.refill_fields)
        self.allowance_summary = label('本轮不使用溶剂或储备波片。', 'muted', True)
        budget_layout.addWidget(self.allowance_summary)
        left.addWidget(resources)
        left.addStretch(1)

        team, team_layout = card('当前队伍')
        team_layout.setSpacing(8)
        heading = row(label('每次开始前都会重新核对', 'muted'),)
        team_layout.addLayout(heading)
        self.team_rows = []
        for index in range(3):
            item = QHBoxLayout()
            index_label = label(f'0{index + 1}', 'eyebrow')
            index_label.setFixedWidth(27)
            name = label('等待检查')
            level = label('—', 'muted')
            item.addWidget(index_label)
            item.addWidget(name, 1)
            item.addWidget(level)
            item.setContentsMargins(0, 5, 0, 5)
            team_layout.addLayout(item)
            self.team_rows.append((name, level))
        self.team_status = label('尚未读取队伍', 'statusChip')
        team_layout.addWidget(self.team_status, 0, Qt.AlignLeft)
        self.team_note = label('进入游戏大世界后点击检查。等级、身份或世界等级不明确时不会开刷。', 'muted', True)
        team_layout.addWidget(self.team_note)
        self.preflight = button('检查当前队伍')
        team_layout.addWidget(self.preflight)
        self.experimental = QCheckBox('允许尝试尚未验证的任务组合')
        self.experimental.setToolTip('仍需通过身份、等级和世界等级检查；不会绕过消费保护。')
        team_layout.addWidget(self.experimental)
        right.addWidget(team)

        support, support_layout = card('内测范围')
        support_layout.addWidget(label('简体中文 · macOS · 游戏保持前台', wrap=True))
        support_layout.addWidget(label('优先验证：玄翎 / 弗洛洛 / 穗穗\n其他组合会明确显示验证状态。', 'muted', True))
        support_layout.addWidget(label('单轮最长 10 分钟。暂停后可继续；关闭面板会先停止任务。', 'muted', True))
        right.addWidget(support)
        right.addStretch(1)
        layout.addLayout(columns)

        progress, progress_layout = card('本轮进度')
        self.progress_card = progress
        progress_layout.setSpacing(8)
        self.progress_title = label('准备就绪后开始', 'cardTitle')
        self.progress_detail = label('尚未启动任务，不会自动操作游戏。', 'muted', True)
        self.progress_bar = QProgressBar()
        self.progress_bar.setRange(0, 1)
        self.progress_bar.setValue(0)
        self.progress_bar.setTextVisible(False)
        progress_layout.addWidget(self.progress_title)
        progress_layout.addWidget(self.progress_detail)
        progress_layout.addWidget(self.progress_bar)
        self.spend = label('波片 0   ·   奖励 0 份   ·   溶剂 0', 'muted')
        self.spend.setWordWrap(True)
        self.start = button('开始刷取', 'primary')
        self.pause = button('暂停')
        self.stop = button('结束本轮', 'danger')
        self.pause.hide()
        self.stop.hide()
        actions = QHBoxLayout()
        actions.addWidget(self.spend, 1)
        actions.addWidget(self.pause)
        actions.addWidget(self.stop)
        actions.addWidget(self.start)
        progress_layout.addLayout(actions)
        layout.addStretch(1)

    def set_compact(self, compact):
        # Stack complete cards on narrow windows; controls retain their readable size.
        self.columns.setDirection(QBoxLayout.TopToBottom if compact else QBoxLayout.LeftToRight)

    @property
    def kind(self):
        return self.kind_group.checkedButton().property('kind')


